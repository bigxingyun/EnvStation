using System.Runtime.Versioning;

// ══════════════════════════════════════════════════════════════════════════════
//  程序集级平台声明
//
//  环境站是 Windows 专属产品（Windows 10 1809 / 构建 17763 及以上，x64 与 ARM64），
//  这一点在《需求分析.md》第 2 章已经确定，不存在跨平台计划。
//
//  为什么必须显式声明：Core 的 TFM 是 net8.0（而不是 net8.0-windows），
//  因为 Abstractions / Core 需要支持被纯 net8.0 的测试工程与未来的 CLI 引用。
//  在不带 -windows 后缀的 TFM 下，分析器会把 Registry / WindowsIdentity 这类 API
//  视为"可能在任何平台调用"，从而对每一处调用报 CA1416。
//
//  在这里做一次程序集级声明，比在几十处调用点上散落 [SupportedOSPlatform] 更好：
//    · 结论只需要在一处评审：这个程序集就是 Windows 专属的；
//    · 不会出现"某个文件忘了标注"导致的规则缺口；
//    · 未来若要真正跨平台，编译器会在移除该声明后一次性把所有平台相关调用点暴露出来。
// ══════════════════════════════════════════════════════════════════════════════

[assembly: SupportedOSPlatform("windows")]
